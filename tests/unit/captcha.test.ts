import { expect, it } from 'vitest'
import { safeCaptchaImage } from '../../src/domain/captcha'

it('accepts only inline raster images generated by the local CAPTCHA backend', () => {
  expect(safeCaptchaImage('data:image/png;base64,YWJj')).toBe(true)
  for (const value of ['https://example.com/image.png', 'javascript:alert(1)', 'data:image/svg+xml;base64,YWJj', 'data:text/html;base64,YWJj']) {
    expect(safeCaptchaImage(value)).toBe(false)
  }
})
